const html = document.documentElement;
const menuButton = document.querySelector('.menu-toggle');
const siteNavigation = document.querySelector('.site-nav');
const languageButtons = document.querySelectorAll('[data-language]');
const metaDescription = document.querySelector('meta[name="description"]');
const ogDescription = document.querySelector('meta[property="og:description"]');
const ogTitle = document.querySelector('meta[property="og:title"]');
const ogLocale = document.querySelector('meta[property="og:locale"]');

let currentLanguage = 'tr';

function t(key) {
  return translations[currentLanguage][key];
}

function menuIsOpen() {
  return menuButton.getAttribute('aria-expanded') === 'true';
}

function updateMenuLabel() {
  menuButton.setAttribute('aria-label', t(menuIsOpen() ? 'menuClose' : 'menuOpen'));
}

function closeMenu({ returnFocus = false } = {}) {
  menuButton.setAttribute('aria-expanded', 'false');
  siteNavigation.classList.remove('is-open');
  updateMenuLabel();

  if (returnFocus) menuButton.focus();
}

function setLanguage(language) {
  if (!translations[language]) return;

  currentLanguage = language;
  html.lang = language;
  html.dataset.language = language;

  document.querySelectorAll('[data-i18n]').forEach((element) => {
    const key = element.dataset.i18n;
    if (translations[language][key]) element.textContent = translations[language][key];
  });

  languageButtons.forEach((button) => {
    const isActive = button.dataset.language === language;
    button.classList.toggle('is-active', isActive);
    button.setAttribute('aria-pressed', String(isActive));
  });

  document.title = t('pageTitle');
  metaDescription.setAttribute('content', t('metaDescription'));
  ogDescription.setAttribute('content', t('ogDescription'));
  ogTitle.setAttribute('content', t('pageTitle'));
  ogLocale.setAttribute('content', language === 'tr' ? 'tr_TR' : 'en_US');
  document.querySelector('.wordmark').setAttribute('aria-label', t('homeLabel'));
  siteNavigation.setAttribute('aria-label', t('mainNav'));
  document.querySelector('.language-switcher').setAttribute('aria-label', t('languageNav'));
  document.querySelector('.hero-index').setAttribute('aria-label', t('fieldsLabel'));
  document.querySelector('.project-list').setAttribute('aria-label', t('projectListLabel'));
  document.querySelector('.status-key').setAttribute('aria-label', t('statusListLabel'));
  updateMenuLabel();

  try {
    localStorage.setItem('uhret-language', language);
  } catch (error) {
    // Language switching remains available if storage is blocked.
  }
}

menuButton.addEventListener('click', () => {
  const shouldOpen = !menuIsOpen();
  menuButton.setAttribute('aria-expanded', String(shouldOpen));
  siteNavigation.classList.toggle('is-open', shouldOpen);
  updateMenuLabel();
});

siteNavigation.querySelectorAll('a').forEach((link) => {
  link.addEventListener('click', () => closeMenu());
});

languageButtons.forEach((button) => {
  button.addEventListener('click', () => setLanguage(button.dataset.language));
});

document.addEventListener('keydown', (event) => {
  if (event.key === 'Escape' && menuIsOpen()) closeMenu({ returnFocus: true });
});

const desktopNavigation = window.matchMedia('(min-width: 821px)');
const handleDesktopNavigation = (event) => {
  if (event.matches) closeMenu();
};

if (desktopNavigation.addEventListener) {
  desktopNavigation.addEventListener('change', handleDesktopNavigation);
} else {
  desktopNavigation.addListener(handleDesktopNavigation);
}

let initialLanguage = 'tr';
try {
  initialLanguage = localStorage.getItem('uhret-language') || 'tr';
} catch (error) {
  initialLanguage = 'tr';
}

if (!translations[initialLanguage]) initialLanguage = 'tr';

setLanguage(initialLanguage);
